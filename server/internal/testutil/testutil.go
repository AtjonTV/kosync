// Package testutil builds throwaway PocketBase instances for the KOsync tests.
//
// Every app is created from an empty data directory and then migrated, so the
// tests always run against the schema that the migrations actually produce
// instead of against a committed fixture that can drift away from them.
package testutil

import (
	// KOReader hashes its passwords with MD5 before sending them, so the server
	// has to speak MD5 to talk to a device at all. The digest is never what is
	// stored: PocketBase hashes it with bcrypt on the way in.
	// bearer:disable go_gosec_blocklist_md5
	"crypto/md5" // #nosec G501 -- see above
	"fmt"
	"strings"
	"testing"
	"time"

	"git.obth.eu/atjontv/kosync/internal/schema"
	"github.com/pocketbase/pocketbase/core"
	"github.com/pocketbase/pocketbase/tests"
	"github.com/pocketbase/pocketbase/tools/filesystem"

	// Registers the KOsync collections in core.AppMigrations.
	_ "git.obth.eu/atjontv/kosync/internal/migrations"
)

// recordIdLength is the fixed width PocketBase expects from a record id.
const recordIdLength = 15

// Md5Hex returns the password digest a KOReader device would send.
func Md5Hex(password string) string {
	// bearer:disable go_gosec_crypto_weak_crypto, go_lang_weak_hash_md5
	return fmt.Sprintf("%x", md5.Sum([]byte(password))) // #nosec G401 -- see the import comment
}

// PadId turns a readable seed into a valid PocketBase record id, so that tests
// can refer to fixtures by name instead of by an autogenerated string.
func PadId(seed string) string {
	return strings.Repeat("0", recordIdLength-len(seed)) + seed
}

// NewApp returns a migrated, isolated PocketBase test instance.
func NewApp(t testing.TB) *tests.TestApp {
	t.Helper()

	app, err := tests.NewTestAppWithConfig(core.BaseAppConfig{
		DataDir:       t.TempDir(),
		EncryptionEnv: "pb_test_env",
	})
	if err != nil {
		t.Fatalf("failed to create test app: %v", err)
	}
	// tests.NewTestAppWithConfig already applies every registered migration,
	// including the KOsync ones pulled in by the blank import above.
	t.Cleanup(app.Cleanup)

	return app
}

// NewUnmigratedApp returns a bootstrapped instance whose KOsync collections do
// not exist yet, the way a fresh data directory looks before the first serve.
//
// It deliberately does not go through tests.NewTestApp, which applies every
// migration on construction.
func NewUnmigratedApp(t testing.TB) core.App {
	t.Helper()

	app := core.NewBaseApp(core.BaseAppConfig{
		DataDir:       t.TempDir(),
		EncryptionEnv: "pb_test_env",
	})

	if err := app.Bootstrap(); err != nil {
		t.Fatalf("failed to bootstrap the app: %v", err)
	}
	t.Cleanup(func() {
		_ = app.ResetBootstrapState()
	})

	return app
}

// CreateUser creates a verified WebUI account.
func CreateUser(t testing.TB, app core.App, id, email, password string) *core.Record {
	t.Helper()

	collection, err := app.FindCollectionByNameOrId(schema.CollectionUsers)
	if err != nil {
		t.Fatalf("failed to find the %q collection: %v", schema.CollectionUsers, err)
	}

	record := core.NewRecord(collection)
	if id != "" {
		record.Id = id
	}
	record.SetEmail(email)
	record.SetPassword(password)
	record.SetVerified(true)

	if err := app.Save(record); err != nil {
		t.Fatalf("failed to create user %q: %v", email, err)
	}

	return record
}

// CreateKoreaderAccount creates a device credential for the given owner.
//
// The plain password is hashed with MD5 first, exactly like the KOReader plugin
// does before it puts the digest into the "x-auth-key" header.
func CreateKoreaderAccount(t testing.TB, app core.App, owner *core.Record, id, username, password string) *core.Record {
	t.Helper()

	collection, err := app.FindCollectionByNameOrId(schema.CollectionKoreaderAccounts)
	if err != nil {
		t.Fatalf("failed to find the %q collection: %v", schema.CollectionKoreaderAccounts, err)
	}

	record := core.NewRecord(collection)
	if id != "" {
		record.Id = id
	}
	record.Set(schema.FieldUsername, username)
	record.Set(schema.FieldOwner, owner.Id)
	record.SetPassword(Md5Hex(password))

	if err := app.Save(record); err != nil {
		t.Fatalf("failed to create koreader account %q: %v", username, err)
	}

	return record
}

