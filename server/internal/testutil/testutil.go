// CreateBook stores a book with the two KOReader hashes set.
//
// The file is a stand-in rather than a real EPUB: the upload hook that would
// read one is a request hook, so a record saved from Go never goes near it, and
// the tests that need real books are the opt-in ones in internal/epub.
func CreateBook(t testing.TB, app core.App, owner *core.Record, id, title, hashBinary, hashFilename string) *core.Record {
	t.Helper()

	collection, err := app.FindCollectionByNameOrId(schema.CollectionBooks)
	if err != nil {
		t.Fatalf("failed to find the %q collection: %v", schema.CollectionBooks, err)
	}

	file, err := filesystem.NewFileFromBytes([]byte("PK\x03\x04 stand-in"), "book.epub")
	if err != nil {
		t.Fatalf("failed to build a stand-in file: %v", err)
	}

	record := core.NewRecord(collection)
	if id != "" {
		record.Id = id
	}
	record.Set(schema.FieldOwner, owner.Id)
	record.Set(schema.FieldFile, file)
	record.Set(schema.FieldTitle, title)
	record.Set(schema.FieldContentHash, hashBinary+hashFilename)
	record.Set(schema.FieldHashBinary, hashBinary)
	record.Set(schema.FieldHashFilename, hashFilename)

	if err := app.Save(record); err != nil {
		t.Fatalf("failed to create book %q: %v", title, err)
	}

	return record
}

// CreateBookCollection stores a hand-made shelf holding the given books.
//
// The books are stored in the order they are passed, because that order is what
// a shelf is: anything that only needs the set of books on it would be a filter
// rather than a collection.
func CreateBookCollection(t testing.TB, app core.App, owner *core.Record, id, name string, books ...*core.Record) *core.Record {
	t.Helper()

	collection, err := app.FindCollectionByNameOrId(schema.CollectionBookCollections)
	if err != nil {
		t.Fatalf("failed to find the %q collection: %v", schema.CollectionBookCollections, err)
	}

	ids := make([]string, 0, len(books))
	for _, book := range books {
		ids = append(ids, book.Id)
	}

	record := core.NewRecord(collection)
	if id != "" {
		record.Id = id
	}
	record.Set(schema.FieldOwner, owner.Id)
	record.Set(schema.FieldName, name)
	record.Set(schema.FieldBooks, ids)

	if err := app.Save(record); err != nil {
		t.Fatalf("failed to create the collection %q: %v", name, err)
	}

	return record
}

// UserToken returns a PocketBase auth token for the given user record.
func UserToken(t testing.TB, user *core.Record) string {
	t.Helper()

	token, err := user.NewAuthToken()
	if err != nil {
		t.Fatalf("failed to create an auth token: %v", err)
	}

	return token
}

// Fixture ids. They are readable on purpose so that a failing HTTP assertion
// names the record it tripped over.
var (
	IdUserA     = PadId("usera")
	IdUserB     = PadId("userb")
	IdAccountA  = PadId("accta")
	IdAccountB  = PadId("acctb")
	IdDocumentA = PadId("docva")
	IdDocumentB = PadId("docvb")
	IdHistoryA  = PadId("hista")
)

// Fixture credentials.
const (
	EmailUserA    = "alice@example.com"
	EmailUserB    = "bob@example.com"
	PasswordUsers = "a-long-enough-password"

	KoUsernameA = "alice-kobo"
	KoPasswordA = "device-secret-a"
	KoUsernameB = "bob-kindle"
	KoPasswordB = "device-secret-b"

	DocumentHashA = "043f11771ef9d191364ac0ba08198d36"
	DocumentHashB = "1a2b3c4d5e6f7a8b9c0d1e2f3a4b5c6d"
)

// Fixture is the seeded two-user world the API tests assert against.
type Fixture struct {
	UserA     *core.Record
	UserB     *core.Record
	AccountA  *core.Record
	AccountB  *core.Record
	DocumentA *core.Record
	DocumentB *core.Record
	HistoryA  *core.Record
}

// Seed creates two users, each with one KOReader credential and one document,
// so that every test can check that one user never sees the other's data.
func Seed(t testing.TB, app core.App) *Fixture {
	t.Helper()

	base := time.Date(2026, 3, 1, 12, 0, 0, 0, time.UTC)

	fixture := &Fixture{}
	fixture.UserA = CreateUser(t, app, IdUserA, EmailUserA, PasswordUsers)
	fixture.UserB = CreateUser(t, app, IdUserB, EmailUserB, PasswordUsers)
	fixture.AccountA = CreateKoreaderAccount(t, app, fixture.UserA, IdAccountA, KoUsernameA, KoPasswordA)
	fixture.AccountB = CreateKoreaderAccount(t, app, fixture.UserB, IdAccountB, KoUsernameB, KoPasswordB)
	fixture.DocumentA = CreateDocument(t, app, fixture.UserA, IdDocumentA, DocumentHashA, 0.25, base)
	fixture.DocumentB = CreateDocument(t, app, fixture.UserB, IdDocumentB, DocumentHashB, 0.5, base)
	fixture.HistoryA = CreateHistoryEntry(t, app, fixture.DocumentA, IdHistoryA, 0.1, base.Add(-2*time.Hour))

	return fixture
}

// SeededApp returns a migrated test app that already contains the Fixture data.
func SeededApp(t testing.TB) *tests.TestApp {
	t.Helper()

	app := NewApp(t)
	Seed(t, app)

	return app
}
